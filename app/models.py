"""Canonical Pydantic v2 schemas and data contracts."""

from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field


class SourceItem(BaseModel):
    """Verified source citation constructed server-side."""

    title: str = Field(description="Title of the source webpage.")
    url: str = Field(description="Canonical URL of the source webpage.")
    last_crawled: str = Field(description="Date the page was last crawled (YYYY-MM-DD).")


class ChatRequest(BaseModel):
    """Incoming user chat query."""

    session_id: str = Field(
        default="default-session",
        description="Unique UUID identifying the chat conversation thread.",
    )
    message: str = Field(
        min_length=1,
        max_length=2000,
        description="User question or prompt (1 to 2000 characters).",
    )


class ChatResponse(BaseModel):
    """Outgoing structured response from the chatbot."""

    answer: str = Field(description="Grounded answer text or polite fallback.")
    sources: List[SourceItem] = Field(
        default_factory=list,
        description="List of verified source citations.",
    )
    answerable: bool = Field(
        default=True,
        description="True if answered from site context; False if fallen back.",
    )
    intent: str = Field(
        default="FACT",
        description="Classified user intent: FACT, DISCOVERY, COMPARISON, or OUT_OF_SCOPE.",
    )
    products_in_context: List[str] = Field(
        default_factory=list,
        description="Names of products referenced or discussed in this turn.",
    )


class HealthResponse(BaseModel):
    """API health status and runtime information."""

    status: str = Field(default="ok", description="Server operational health.")
    environment: str = Field(description="'vercel' if cloud serverless, 'local' otherwise.")
    kb_status: str = Field(description="Knowledge base availability status.")


class ProductItem(BaseModel):
    """Product catalog entry."""

    name: str = Field(description="Exact product or service name.")
    category: str = Field(description="Product category (e.g. Credit Cards, Accounts, Loans).")
    url: str = Field(description="URL to the product page on the company website.")
    page_id: Optional[str] = Field(default=None, description="Internal page record ID.")


class LLMAnswerOutput(BaseModel):
    """Structured JSON schema enforced during Gemini generation."""

    answerable: bool = Field(
        description="True if context has sufficient information to answer; False otherwise.",
    )
    answer: str = Field(
        description="Grounded answer containing exact figures and conditions, or concise refusal.",
    )
    used_chunk_ids: List[str] = Field(
        default_factory=list,
        description="List of context chunk IDs directly used to formulate the answer.",
    )
    reasoning: Optional[str] = Field(
        default=None,
        description="Short 1-sentence explanation of answerability or refusal.",
    )


class CrawledPageRecord(BaseModel):
    """Database record for a crawled or scraped webpage."""

    id: str
    url: str
    title: str
    content_hash: str
    crawled_at: str
    status: str = "indexed"  # "indexed", "skipped", "error"
    skip_reason: Optional[str] = None
    markdown_content: Optional[str] = None


class ChunkRecord(BaseModel):
    """Individual heading-aware text chunk."""

    id: str
    page_id: str
    product_id: Optional[str] = None
    section_path: str
    chunk_index: int
    text: str
    content_hash: str


# -----------------------------------------------------------------------------
# Diagnostics & Testing Models (for Swagger UI /docs)
# -----------------------------------------------------------------------------

class LLMTestRequest(BaseModel):
    """Payload to test LLM generation across configured providers."""

    provider: Literal["auto", "xai", "gemini", "openrouter"] = Field(
        default="auto",
        description="Target LLM provider to invoke. 'auto' selects xAI if key present, else Gemini, then OpenRouter.",
    )
    prompt: str = Field(
        default="What are Emirates NBD's core banking values? Answer in 2 short sentences.",
        description="Prompt message to send to the LLM.",
    )
    temperature: float = Field(
        default=0.2,
        ge=0.0,
        le=1.0,
        description="Sampling temperature.",
    )


class LLMTestResponse(BaseModel):
    """Diagnostic response from an LLM invocation test."""

    status: str = Field(description="'ok' if generated successfully; 'error' otherwise.")
    provider: str = Field(description="Actual provider invoked ('xai', 'gemini', 'openrouter', 'deterministic').")
    model: str = Field(description="Model identifier invoked (e.g. 'grok-2-latest', 'gemini-2.0-flash').")
    response: str = Field(description="Text output generated by the model.")
    latency_ms: float = Field(description="Round-trip latency in milliseconds.")
    configured: bool = Field(description="True if an API key for the requested provider is present in the environment.")
    error: Optional[str] = Field(default=None, description="Detailed error description if call failed.")


class ProviderHealthReport(BaseModel):
    """Comprehensive environment and provider readiness report."""

    timestamp: str = Field(description="ISO 8601 timestamp of health evaluation.")
    environment: str = Field(description="Host environment ('local' or 'vercel').")
    all_ready: bool = Field(description="True if all critical services are operational.")
    providers: Dict[str, Dict[str, Any]] = Field(
        description="Detailed status dictionary for each provider (xAI, Gemini, OpenRouter, Qdrant, Firecrawl, TinyFish).",
    )


class RetrievalTestRequest(BaseModel):
    """Payload to test Qdrant hybrid vector retrieval in isolation."""

    query: str = Field(
        default="U By Emaar Signature Credit Card annual fee",
        description="Search query to test hybrid retrieval against Qdrant.",
    )
    top_k: int = Field(
        default=5,
        ge=1,
        le=20,
        description="Number of top chunks to retrieve.",
    )
    category: Optional[str] = Field(
        default=None,
        description="Optional category filter (e.g. 'Credit Cards', 'Savings Accounts').",
    )


class ChunkResultItem(BaseModel):
    """Individual chunk returned from isolated retrieval test."""

    chunk_id: str
    product_name: str
    category: str
    score: float
    url: str
    title: str
    text_snippet: str


class RetrievalTestResponse(BaseModel):
    """Diagnostic response from Qdrant hybrid retrieval test."""

    query: str
    top_k: int
    results_count: int
    max_score: float
    latency_ms: float
    chunks: List[ChunkResultItem]


class RewriteTestRequest(BaseModel):
    """Payload to test query rewriting and routing in isolation."""

    raw_query: str = Field(
        default="what is its annual fee?",
        description="Incoming user query (can include pronouns or follow-up phrases).",
    )
    history: List[Dict[str, str]] = Field(
        default_factory=lambda: [
            {"role": "user", "content": "Tell me about U By Emaar Signature Credit Card"},
            {"role": "assistant", "content": "The U By Emaar Signature Credit Card is a premium lifestyle card."},
        ],
        description="Preceding conversational history.",
    )


class RewriteTestResponse(BaseModel):
    """Diagnostic response from query rewriting and routing test."""

    raw_query: str
    standalone_query: str
    intent: str
    target_product: Optional[str] = None
    target_category: Optional[str] = None
    excluded_products: List[str] = []
    sub_queries: List[str] = []
